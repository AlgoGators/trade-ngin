namespace trade_ngin::contract_rolls {

/// A calendar date (the UTC date of a daily bar).
using Day = std::chrono::sys_days;

/// "YYYY-MM-DD".
std::string ymd(Day day);
/// Parses "YYYY-MM-DD"; throws std::invalid_argument on anything else.
Day parse_ymd(const std::string& text);

/// Thrown when a date the rule needs falls outside the holiday calendar's coverage. The calendar
/// cannot tell "open" from "unknown" there, so the per-contract roll code fails closed; the API
/// (contract_rolls.hpp) turns it into an error Result.
class CalendarCoverageError : public std::runtime_error {
public:
    using std::runtime_error::runtime_error;
};

/**
 * @brief The trading days of one product, as the roll rule counts them.
 *
 * Monday to Friday less the days the exchange publishes no settlement for the product (a Globex
 * session on a holiday belongs to the next trade date, so it is not one). A Saturday bar (MBT) and
 * a Sunday bar are never trading days. Outside the calendar's coverage every query throws
 * CalendarCoverageError. A product's calendar comes from FuturesCalendar::for_root.
 */
class TradingCalendar {
public:
    /// A calendar that covers no date (every query throws); Result needs a default.
    TradingCalendar()
        : is_holiday_([](const std::string&) { return false; }),
          covers_([](const std::string&) { return false; }) {}
    /// `is_holiday` and `covers` take a "YYYY-MM-DD" string.
    TradingCalendar(std::function<bool(const std::string&)> is_holiday,
                    std::function<bool(const std::string&)> covers);

    bool is_trading_day(Day day) const;
    /// The n-th trading day strictly before `day` (n >= 1).
    Day trading_day_before(Day day, int n = 1) const;
    /// The first trading day on or after `day`.
    Day trading_day_on_or_after(Day day) const;
    /// The last trading day of a month.
    Day last_trading_day_of_month(int year, unsigned month) const;
    /// The n-th trading day of a month (n >= 1).
    Day nth_trading_day_of_month(int year, unsigned month, int n) const;

private:
    void require_covered(Day day) const;
    std::function<bool(const std::string&)> is_holiday_;
    std::function<bool(const std::string&)> covers_;
};

/**
 * @brief The futures exchanges' own calendars: the roll rule's
 *        trading days, per exchange and per product group, from
 *        include/trade_ngin/core/futures_holidays.json (generated by
 *        scripts/generate_futures_holidays.py, which also --checks it).
 *
 * NOT the equity calendar (HolidayChecker, holidays.json, the NYSE's): CME Group traded on days the
 * NYSE closed (2012-10-29 and 10-30, 2018-12-05, 2025-01-09) and closes some groups on days it
 * opens others (a Good Friday with the employment report). The file lists, per exchange, the
 * product groups and their roots, the years it covers, and each closure with the groups it closes.
 * A day is a trading day for a root when it is a weekday, inside the coverage, and no closure lists
 * the root's group. Each exchange is its own calendar (ICE, for the softs, is added as its own).
 */
class FuturesCalendar {
public:
    /// Where the file is: TRADE_NGIN_FUTURES_HOLIDAYS_JSON (as given), else the first that exists of
    /// include/trade_ngin/core/futures_holidays.json, futures_holidays.json and
    /// /etc/trade_ngin/futures_holidays.json; else the first (so the load error names it).
    static std::string resolve_path();
    /// Loads and checks the file: an error for a missing or malformed file, a root in two groups,
    /// a closure naming an unknown group or a date outside the coverage.
    static Result<FuturesCalendar> load(const std::string& path);

    /// The trading-day calendar of `root`; an error for a root no exchange lists.
    Result<TradingCalendar> for_root(const std::string& root) const;
    /// "CME" and "grains" for ZC; empty strings for an unknown root.
    std::string exchange_of(const std::string& root) const;
    std::string group_of(const std::string& root) const;

private:
    struct Exchange {
        int first_year{0};
        int last_year{0};
        std::map<std::string, std::string> group_of_root;
        std::map<std::string, std::set<std::string>> closed_by_group;  ///< group -> "YYYY-MM-DD"
    };
    std::shared_ptr<const std::map<std::string, Exchange>> exchanges_;
};

/**
 * @brief The exchange rules for a contract's last trading day and first notice day, by root.
 *
 * The rules count trading days on the product's own futures calendar (FuturesCalendar). The
 * last trading day is READ from contract_ohlcv_1d.expiration; this rule only cross-checks it (a mismatch is a WARN). The first
 * notice day has no column and comes from the rule.
 *
 * `month` is the contract's delivery month (the month code), `year` its delivery year.
 */
struct ExchangeRules {
    /// The last trading day by the exchange's rule; throws std::invalid_argument for an unknown root.
    static Day last_trading_day(const std::string& root, int year, unsigned month,
                                const TradingCalendar& cal);
    /// The first notice day, for the physically delivered contracts whose notice period opens
    /// before the last trading day (metals, grains, Treasuries, live cattle); nullopt for the rest
    /// (cash settled, or delivery only after the last trade).
    static std::optional<Day> first_notice_day(const std::string& root, int year, unsigned month,
                                               const TradingCalendar& cal);
    /// Whether the root is one the rules know.
    static bool knows(const std::string& root);
};

}  // namespace trade_ngin::contract_rolls
