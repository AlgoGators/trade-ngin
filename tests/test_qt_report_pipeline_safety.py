"""Fast, offline contracts for the QT certification harness.

These tests never start Docker, open a socket, import the AlgoLens application,
or execute the C++ probe.  They protect the test-only safety and evidence code
that must run *before* the disposable integration environment is created.
"""

import importlib.util
import json
