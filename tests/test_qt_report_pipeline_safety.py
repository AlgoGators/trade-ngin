def test_manifest_hashes_artifacts_and_does_not_invent_send_telemetry(tmp_path):
    artifact = tmp_path / "synthetic.csv"
    artifact.write_text("strategy,symbol,quantity\nA,ES,7\n", encoding="utf-8")
    manifest_path = tmp_path / "evidence.json"

    qt.write_evidence_manifest(
        manifest_path,
        scope={"portfolio_id": "BOOK_A", "strategy_id": "LIVE_QT_PIPELINE"},
        report_date="2026-09-21",
        checks=[{"name": "synthetic", "passed": True}],
        artifacts=[artifact],
    )

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["artifacts"][0]["sha256"] == qt.sha256_file(artifact)
    assert manifest["email_send_attempts"]["status"] == "unavailable"
    assert manifest["email_send_attempts"]["count"] is None
    assert manifest["smtp_tested"] is False
    assert manifest["delivery_verified"] is False


def test_fifo_wait_fails_when_probe_exits_before_signal(tmp_path):
    """A broken probe must fail immediately instead of hanging on a FIFO open."""
    fifo = tmp_path / "ready.fifo"
    os.mkfifo(fifo, 0o600)
    fifo_fd = os.open(fifo, os.O_RDWR | os.O_NONBLOCK)
    process = subprocess.Popen(
        [sys.executable, "-S", "-c", "raise SystemExit(17)"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    try:
        with pytest.raises(RuntimeError, match="exited before FIFO signal"):
            qt.wait_for_fifo_signal(process, fifo_fd, "snapshot-loaded", timeout=5)
    finally:
        if process.poll() is None:
            process.kill()
        process.communicate()
        os.close(fifo_fd)


def test_network_guard_requires_only_loopback_and_no_ipv4_routes(tmp_path):
    """An external interface or route must fail the pre-side-effect guard."""
    route = tmp_path / "route"
    route.write_text("Iface\tDestination\tGateway\n", encoding="ascii")
    evidence = qt.require_isolated_network_namespace(
        interface_provider=lambda: [(1, "lo")], ipv4_route_path=route)
    assert evidence["interfaces"] == ["lo"]
    assert evidence["ipv4_route_count"] == 0

    with pytest.raises(qt.UnsafeCertificationInput, match="only interface lo"):
        qt.require_isolated_network_namespace(
            interface_provider=lambda: [(1, "lo"), (2, "eth0")],
            ipv4_route_path=route,
        )

    route.write_text(
        "Iface\tDestination\tGateway\nlo\t00000000\t00000000\n",
        encoding="ascii",
    )
    with pytest.raises(qt.UnsafeCertificationInput, match="no IPv4 routes"):
        qt.require_isolated_network_namespace(
            interface_provider=lambda: [(1, "lo")], ipv4_route_path=route)
